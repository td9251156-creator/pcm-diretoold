// Verificação de ponta a ponta exigida pela CI, com ferramenta isolada do aplicativo.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { iniciarServidor, aguardarOffline, executarComRecursos } from './navegador.mjs';

const ferramenta = process.env.PCM_PLAYWRIGHT || new URL('../ferramentas/navegador/node_modules/playwright/index.mjs', import.meta.url).href;
const { chromium } = await import(ferramenta);
const raiz = fileURLToPath(new URL('../', import.meta.url));
await executarComRecursos({
  criarServidor: () => iniciarServidor({ raiz }),
  criarNavegador: () => chromium.launch({
    executablePath: process.env.PCM_CHROMIUM || undefined,
    args: process.env.PCM_SEM_SANDBOX === '1' ? ['--no-sandbox'] : [],
    timeout: 20000,
  }),
  executar: async ({ navegador: browser }) => {
    const contexto = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
    contexto.setDefaultTimeout(15000);
    contexto.setDefaultNavigationTimeout(30000);
    const page = await contexto.newPage();
    const erros = [];
    page.on('pageerror', (e) => erros.push(e.message));
    await page.goto('http://127.0.0.1:4175/');
    await page.getByRole('heading', { name: 'Plano de manutenção preventiva a partir da sua lista de equipamentos' }).waitFor();
    await page.getByRole('link', { name: '2. Equipamentos' }).focus();
    await page.keyboard.press('Enter');
    await page.waitForURL('**/#equipamentos');
    await page.waitForFunction(() => document.activeElement?.id === 'conteudo');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'conteudo');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'A página excedeu a largura do celular');
    await page.locator('.pular').focus();
    await page.keyboard.press('Enter');
    assert.ok(page.url().endsWith('#equipamentos'), 'Pular para conteúdo não deve trocar de tela');
    // Cadastros reais: o rascunho de M1 não pode sumir ao adicionar uma pessoa em M3.
    const primeiroEquipamento = page.locator('.equip').first();
    await primeiroEquipamento.locator('summary').click();
    const setorOriginal = await primeiroEquipamento.locator('[data-campo="setor"]').inputValue();
    await primeiroEquipamento.locator('[data-campo="setor"]').fill('');
    await page.getByRole('link', { name: 'Cadastros', exact: true }).click();
    await page.locator('#g-nome').fill('Indústria Exemplo');
    await page.locator('#g-pessoa-nome').fill('Pessoa A');
    await page.locator('#g-funcao').fill('Responsável fictício');
    await page.locator('#g-especialidade').fill('Elétrica');
    await page.locator('#salvar-pessoa').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.pessoas.length === 1);
    assert.equal(await page.locator('#g-nome').inputValue(), 'Indústria Exemplo', 'Salvar M3 apagou o rascunho de M1');
    const pessoaId = await page.evaluate(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.pessoas[0].id);
    await page.locator('#g-elaborador').selectOption(pessoaId);
    await page.locator('#salvar-organizacao').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.organizacao.nome === 'Indústria Exemplo');
    await page.locator('#g-aderencia').fill('90');
    await page.locator('#salvar-metas').click();
    await page.locator('#g-referencia').fill('Referência fictícia');
    await page.locator('#g-status').selectOption('verificado');
    await page.locator('#salvar-requisito').click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.requisitos.length), 0);
    await page.locator('#g-versao').fill('1');
    await page.locator('#g-data').fill('2026-10-20');
    await page.locator('#g-fonte').fill('https://example.org/referencia');
    await page.locator('#salvar-requisito').click();
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#g-nome')?.value === 'Indústria Exemplo');
    assert.equal(await page.locator('#g-aderencia').inputValue(), '90');
    await page.getByRole('button', { name: 'Editar Pessoa A', exact: true }).click();
    await page.locator('#g-funcao').fill('Responsável revisado');
    await page.locator('#salvar-pessoa').click();
    assert.ok((await page.locator('#conteudo').innerText()).includes('Responsável revisado'));
    await page.getByRole('button', { name: 'Editar referência', exact: true }).click();
    page.once('dialog', d => d.accept());
    await page.getByRole('button', { name: 'Remover referência', exact: true }).click();
    assert.equal(await page.locator('#form-requisito [name="id"]').inputValue(), '', 'Remover referência precisa limpar seu editor');
    assert.equal(await page.locator('#salvar-requisito').textContent(), 'Adicionar referência');
    await page.getByRole('link', { name: '2. Equipamentos' }).click();
    await page.locator('.equip [data-campo="setor"]').first().fill(setorOriginal);
    await page.getByRole('link', { name: 'Criticidade', exact: true }).click();
    for (const [i, nota] of [3, 1, 1, 1, 1].entries()) await page.locator('.avaliacao').first().locator(`[name="nota-${i}"]`).selectOption(String(nota));
    await page.locator('.avaliacao').first().getByRole('button').click();
    assert.ok((await page.locator('.avaliacao').first().innerText()).includes('Classe: A'));
    await page.getByRole('link', { name: 'Plano Mestre', exact: true }).click();
    await page.locator('#lista-plano select').first().selectOption(pessoaId);
    await page.getByRole('link', { name: 'Falhas', exact: true }).click();
    await page.locator('#falha-equipamento').selectOption({ index: 1 });
    await page.locator('#g-sintoma').fill('Ruído fictício');
    await page.locator('#g-horasParada').fill('1.5');
    await page.locator('#salvar-falha').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.falhas.length === 1);
    await page.getByRole('button', { name: 'Corrigir registro' }).click();
    await page.locator('#g-acao').fill('Inspeção fictícia');
    await page.locator('#salvar-falha').click();
    assert.ok((await page.locator('#conteudo').innerText()).includes('Inspeção fictícia'));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Gestão deve caber no celular');
    await page.goto('http://127.0.0.1:4175/#revisao');
    const capacidade = page.locator('.capacidade').first();
    const aguardarRedesenho = () => page.evaluate(() => new Promise((resolve) =>
      requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await capacidade.waitFor();
    const idCapacidade = await capacidade.getAttribute('id');
    const idProximaCapacidade = await page.locator('.capacidade').nth(1).getAttribute('id');
    await capacidade.focus();
    for (const [tecla, valor] of [['ArrowUp', 0.5], ['ArrowUp', 1], ['ArrowDown', 0.5]]) {
      await capacidade.press(tecla);
      await aguardarRedesenho();
      await page.waitForFunction((id) => document.activeElement?.id === id, idCapacidade);
      assert.equal(Number(await capacidade.inputValue()), valor);
    }
    await capacidade.fill('2');
    await capacidade.press('Tab');
    await aguardarRedesenho();
    await page.waitForFunction((id) => document.activeElement?.id === id, idProximaCapacidade);
    await page.reload();
    await capacidade.waitFor();
    assert.equal(Number(await capacidade.inputValue()), 2);
    await capacidade.fill('');
    await capacidade.press('Tab');
    await aguardarRedesenho();
    await page.waitForFunction((id) => document.activeElement?.id === id, idProximaCapacidade);
    await page.goto('http://127.0.0.1:4175/#biblioteca');
    await page.locator('#importar-json').setInputFiles({ name: 'invalido.json', mimeType: 'application/json', buffer: Buffer.from('null') });
    await page.waitForFunction(() => document.querySelector('#mensagens').textContent.includes('Biblioteca não importada'));
    assert.equal(await page.locator('#tipos > details').count(), 4);
    await page.goto('http://127.0.0.1:4175/#execucao');
    await page.locator('#checklists details > summary').first().click();
    const tarefa = page.locator('#checklists form').first();
    await tarefa.locator('[name="concluida"]').check();
    await tarefa.locator('[name="observacao"]').fill('Conferência fictícia do roteiro de teste');
    const dataPrevista = await tarefa.locator('[name="dataPrevista"] option').nth(1).getAttribute('value');
    await tarefa.locator('[name="dataPrevista"]').selectOption(dataPrevista);
    await tarefa.getByRole('button').click();
    await page.waitForFunction(() => Object.keys(JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).execucoes).length === 1);
    await page.reload();
    await page.locator('#checklists details > summary').first().click();
    assert.equal(await page.locator('#checklists form [name="concluida"]').first().isChecked(), true);
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.historico.length), 1);
    await page.locator('#checklists form').first().getByRole('button').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.historico.length === 2);
    page.once('dialog', d => d.accept());
    await page.locator('[data-cancelar]').first().click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.historico.filter(h => h.cancelada).length === 1);
    await page.getByRole('link', { name: 'Mensal', exact: true }).click();
    await page.locator('#ano-mensal').fill(dataPrevista.slice(0, 4));
    await page.locator('#ano-mensal').press('Tab');
    assert.equal(await page.locator('#resumo-mensal tbody tr').nth(Number(dataPrevista.slice(5, 7)) - 1).locator('td').nth(2).textContent(), '1');
    const resumoAntes = await page.locator('#resumo-mensal').innerText();
    await page.locator('#ano-mensal').fill('');
    await page.locator('#ano-mensal').press('Tab');
    assert.equal(await page.locator('#ano-mensal').evaluate(c => c.checkValidity()), false);
    assert.equal(await page.locator('#resumo-mensal').innerText(), resumoAntes, 'Ano vazio não deve gerar resumo do ano zero');
    await page.getByRole('link', { name: '1. Início' }).click();
    const [backup] = await Promise.all([page.waitForEvent('download'), page.locator('#baixar-backup').click()]);
    const bytesBackup = await readFile(await backup.path());
    const backupCompleto = JSON.parse(bytesBackup.toString('utf8'));
    assert.equal(backupCompleto.versao, 2);
    assert.equal(backupCompleto.rascunho.gestao.pessoas.length, 1);
    assert.equal(backupCompleto.rascunho.gestao.historico.length, 2);
    assert.equal(backupCompleto.rascunho.gestao.falhas.length, 1);
    page.on('dialog', (d) => d.accept());
    await page.locator('#em-branco').click();
    await page.getByRole('link', { name: '1. Início' }).click();
    await page.locator('#restaurar-backup').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: bytesBackup });
    await page.waitForFunction(() => document.querySelector('#mensagens').textContent.includes('Backup restaurado'));
    assert.equal(await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).execucoes).length), 1);
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('pcm-direto:rascunho:v1')).gestao.organizacao.nome), 'Indústria Exemplo');
    await page.getByRole('link', { name: '2. Equipamentos' }).click();
    await page.locator('.equip').first().waitFor();
    const quantidade = await page.locator('.equip').count();
    await page.locator('.equip > summary').first().click();
    await page.locator('.equip .remover').first().click();
    await page.waitForFunction((q) => document.querySelectorAll('.equip').length === q, quantidade - 1);
    assert.equal(await page.locator('.equip').count(), quantidade - 1);
    await page.locator('#desfazer-remocao').click();
    await page.waitForFunction((q) => document.querySelectorAll('.equip').length === q, quantidade);
    assert.equal(await page.locator('.equip').count(), quantidade);
    await page.getByRole('link', { name: 'Cadastros', exact: true }).click();
    await page.getByRole('button', { name: 'Inativar Pessoa A', exact: true }).click();
    await page.getByRole('button', { name: 'Reativar Pessoa A', exact: true }).click();
    await page.getByRole('link', { name: '2. Equipamentos' }).click();
    await page.goto('http://127.0.0.1:4175/#impressao');
    await page.locator('#filtro-setor').selectOption('PRD');
    await page.locator('#filtro-especialidade').selectOption('Elétrica');
    assert.ok((await page.locator('#folha-cronograma tbody .tag').allTextContents()).every((tag) => tag.startsWith('PRD-')));
    assert.ok((await page.locator('#folha-cronograma tbody .tag').count()) > 0);
    assert.ok((await page.locator('#folha-cronograma').innerText()).includes('Filtros: PRD · Elétrica'));
    await page.goto('http://127.0.0.1:4175/#execucao');
    await aguardarOffline(page);
    await contexto.setOffline(true);
    await page.reload();
    await page.getByRole('heading', { name: 'Checklist de execução', exact: true }).waitFor();
    await page.getByRole('link', { name: '4. Entrega' }).click();
    await page.getByRole('heading', { name: 'Entrega', exact: true }).waitFor();
    assert.ok((await page.locator('#conteudo').innerText()).includes('aguardando modelo'));
    assert.equal(await page.locator('#baixar-pcmd').count(), 0, 'Não criar download de template PCMD nesta entrega');
    for (const [botao, extensao] of [['#baixar-xlsx', '.xlsx'], ['#baixar-docx', '.docx']]) {
      const [arquivo] = await Promise.all([page.waitForEvent('download'), page.locator(botao).click()]);
      assert.ok(arquivo.suggestedFilename().endsWith(extensao));
      const bytes = await readFile(await arquivo.path());
      assert.ok(bytes.length > 5000);
      assert.equal(bytes.subarray(0, 2).toString(), 'PK');
    }
    await contexto.setOffline(false);
    await page.goto('http://127.0.0.1:4175/#revisao');
    await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Falha simulada de armazenamento'); }; });
    await page.locator('.capacidade').first().fill('0.5');
    await page.locator('.capacidade').first().press('Tab');
    await page.locator('#aviso-armazenamento').waitFor({ state: 'visible' });
    await page.reload();
    await page.evaluate(() => localStorage.setItem('pcm-direto:rascunho:v1', '{'));
    await page.reload();
    await page.getByRole('button', { name: 'Baixar dados originais para recuperação' }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem('pcm-direto:rascunho:v1')), '{');
    assert.deepEqual(erros, []);
    console.log('Aprovado: cadastros, criticidade, responsáveis, mensal, falhas, histórico/cancelamento, backup v2, celular, teclado, importação, desfazer, filtros, recuperação e XLSX/DOCX offline, sem templates novos.');
  },
});
